"""Generate gliders.js (the glider types for converting sensor logs) from the firmware's tables, so the browser replay
uses the device's polars and flap speeds: components/glider/PolarTable.txt and FlapTable.txt. sens2rec.py reads the
same table through gliders().
  python3 tools/airmass_sim/web/make_gliders.py"""
import csv
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.join(HERE, "..", "..", "..", "components", "glider")
VNE = 270.0  # km/h, the device's default Vne setting (v_max): the top of the flap recommendation
OWN_VNE = {"ASG 29/18": 280.0, "ASG 29/15": 285.0}  # km/h, the gliders of the real-flight logs with their own Vne

def entries(path):
    """the { ... } rows of a table: their comma separated fields, strings unquoted"""
    for line in open(path):
        m = re.match(r"\s*\{(.*)\}", line.split("//")[0])
        if m:  # fields split at commas outside quotes ("Salto 13,6m")
            yield [x.strip() for x in next(csv.reader([m.group(1)], skipinitialspace=True))]


def gliders():
    """the glider types by name: id (the device's glider type), wingload, polar points, area, vne, and the flap speeds
    of flapped gliders"""
    polars = {}
    for f in entries(os.path.join(TABLES, "PolarTable.txt")):
        # index, type, wingload, v1, w1, v2, w2, v3, w3, max ballast, wing area, flags (bit 0: flaps), ...
        idx, name = int(f[0]), f[1]
        v = [float(x) for x in f[2:12]]
        wingload, v1, w1, v2, w2, v3, w3, ballast, area, flags = v
        polars[idx] = dict(name=name, wingload=wingload, polar=[[v1, w1], [v2, w2], [v3, w3]], area=area, flapped=int(flags) & 1)

    flaps = {}
    for f in entries(os.path.join(TABLES, "FlapTable.txt")):
        # index, up to 7 flap speeds [km/h] (0: none), their labels
        flaps[int(f[0])] = [int(x) for x in f[1:8] if int(x) > 0]

    out = {}
    for idx, p in sorted(polars.items(), key=lambda kv: kv[1]["name"].lower()):
        if p["area"] <= 0 or p["wingload"] <= 0:
            continue
        g = dict(id=idx, wingload=p["wingload"], polar=p["polar"], area=p["area"], vne=OWN_VNE.get(p["name"], VNE))
        if p["flapped"] and idx in flaps:
            g["flaps"] = flaps[idx]
        out[p["name"]] = g
    return out


if __name__ == "__main__":
    out = gliders()
    with open(os.path.join(HERE, "gliders.js"), "w") as f:
        f.write("// Generated by make_gliders.py from components/glider/PolarTable.txt and FlapTable.txt: do not edit.\n")
        f.write("(function (root) {\n  const GLIDER_TABLE = " + json.dumps(out, separators=(",", ":")) + ";\n")
        f.write('  if (typeof module !== "undefined" && module.exports) module.exports = GLIDER_TABLE;\n  else root.GLIDER_TABLE = GLIDER_TABLE;\n')
        f.write('})(typeof globalThis !== "undefined" ? globalThis : this);\n')
    print(f"{len(out)} gliders, {sum('flaps' in g for g in out.values())} with flap speeds -> gliders.js")
